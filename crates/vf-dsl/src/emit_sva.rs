use std::collections::BTreeSet;
use std::fmt::Write;
use vf_ir::Module;

use crate::ast::*;

/// Export a `.vfc` v1.0 contract as a portable, standalone IEEE 1800 SystemVerilog SVA
/// checker module + `bind` statement compatible with VeloFormal, SymbiYosys, Questa, and JasperGold.
pub fn emit_sva(contract: &Contract, target_module_ir: Option<&Module>) -> String {
    let mut out = String::new();
    let chk_name = format!("{}_sva", contract.name);

    // Collect referenced DUT signal names (excluding parameters, symbolics, ghosts).
    let mut local_names: BTreeSet<String> = BTreeSet::new();
    for p in &contract.params {
        local_names.insert(p.name.clone());
    }
    for s in &contract.symbolics {
        local_names.insert(s.name.clone());
    }
    for g in &contract.ghosts {
        local_names.insert(g.name.clone());
    }

    let mut ports: BTreeSet<String> = BTreeSet::new();
    if let Some(clk) = &contract.clock {
        ports.insert(clk.signal.clone());
    }
    if let Some(rst) = &contract.reset {
        collect_idents(&rst.cond, &local_names, &mut ports);
    }
    for r in &contract.requires {
        collect_idents(&r.expr, &local_names, &mut ports);
    }
    for inv in &contract.invariants {
        collect_idents(&inv.expr, &local_names, &mut ports);
    }
    for op in &contract.operations {
        collect_idents(&op.trigger, &local_names, &mut ports);
        for ens in &op.ensures {
            if let EnsureTiming::Until(ev) = &ens.timing {
                collect_idents(ev, &local_names, &mut ports);
            }
            collect_idents(&ens.response, &local_names, &mut ports);
        }
    }
    for u in &contract.updates {
        collect_update_idents(&u.stmts, &local_names, &mut ports);
    }
    for f in &contract.fairs {
        collect_idents(&f.expr, &local_names, &mut ports);
    }
    for ev in &contract.eventuallys {
        collect_idents(&ev.expr, &local_names, &mut ports);
    }
    for c in &contract.covers {
        collect_idents(&c.expr, &local_names, &mut ports);
    }
    for u in &contract.uses {
        for a in &u.args {
            collect_idents(a, &local_names, &mut ports);
        }
    }

    let _ = writeln!(
        out,
        "// Generated by VeloFormal `emit-sva` from contract `{}` for `{}`",
        contract.name, contract.target_module
    );
    let _ = write!(out, "module {chk_name}");
    if !contract.params.is_empty() {
        out.push_str(" #(\n");
        for (i, p) in contract.params.iter().enumerate() {
            let comma = if i + 1 < contract.params.len() { "," } else { "" };
            let _ = writeln!(out, "    parameter int {} = 1{comma}", p.name);
        }
        out.push(')');
    }
    out.push_str(" (\n");
    let port_list: Vec<String> = ports.into_iter().collect();
    for (i, pname) in port_list.iter().enumerate() {
        let comma = if i + 1 < port_list.len() { "," } else { "" };
        let decl = if let Some(m) = target_module_ir {
            if let Some(sid) = m.find_signal(pname) {
                let s = m.signal(sid);
                let sign = if s.signed { "signed " } else { "" };
                if s.width == 1 {
                    format!("input logic {sign}{pname}")
                } else {
                    format!("input logic {sign}[{}:0] {pname}", s.width - 1)
                }
            } else {
                format!("input logic {pname}")
            }
        } else {
            format!("input logic {pname}")
        };
        let _ = writeln!(out, "    {decl}{comma}");
    }
    out.push_str(");\n");

    let clk_event = match &contract.clock {
        Some(c) => {
            let edge = match c.edge {
                EdgeKind::PosEdge => "posedge",
                EdgeKind::NegEdge => "negedge",
            };
            format!("@({edge} {})", c.signal)
        }
        None => "@(posedge clk)".to_string(),
    };
    let rst_sv = contract
        .reset
        .as_ref()
        .map(|r| expr_to_sv(&r.cond))
        .unwrap_or_else(|| "1'b0".to_string());

    // Emit post-reset history counter for safe `prev`/`rose`/`fell`/`stable`.
    let _ = writeln!(out, "    logic [7:0] vf_hist;");
    let _ = writeln!(out, "    initial vf_hist = 8'd0;");
    let _ = writeln!(out, "    always_ff {clk_event} begin");
    let _ = writeln!(out, "        if ({rst_sv}) vf_hist <= 8'd0;");
    let _ = writeln!(
        out,
        "        else if (vf_hist < 8'd255) vf_hist <= vf_hist + 8'd1;"
    );
    let _ = writeln!(out, "    end\n");

    // Symbolic variables
    for s in &contract.symbolics {
        let attr = match s.kind {
            SymbolicKind::AnyConst => "(* anyconst *)",
            SymbolicKind::AnySeq => "(* anyseq *)",
        };
        let sign = if s.signed { "signed " } else { "" };
        let range = if s.width == 1 {
            String::new()
        } else {
            format!("[{}:0] ", s.width - 1)
        };
        let _ = writeln!(out, "    {attr} logic {sign}{range}{};", s.name);
    }

    // Ghost variables & updates
    for g in &contract.ghosts {
        let sign = if g.signed { "signed " } else { "" };
        let range = if g.width == 1 {
            String::new()
        } else {
            format!("[{}:0] ", g.width - 1)
        };
        let _ = writeln!(out, "    logic {sign}{range}{};", g.name);
        if let Some(init) = &g.init {
            let _ = writeln!(out, "    initial {} = {};", g.name, expr_to_sv(init));
        }
    }
    if !contract.updates.is_empty() {
        let _ = writeln!(out, "    always_ff {clk_event} begin");
        let _ = writeln!(out, "        if ({rst_sv}) begin");
        for g in &contract.ghosts {
            if let Some(init) = &g.init {
                let _ = writeln!(out, "            {} <= {};", g.name, expr_to_sv(init));
            }
        }
        let _ = writeln!(out, "        end else begin");
        for u in &contract.updates {
            emit_sv_update_stmts(&u.stmts, 3, &mut out);
        }
        let _ = writeln!(out, "        end");
        let _ = writeln!(out, "    end\n");
    }

    // `require` -> `assume property`
    for r in &contract.requires {
        let _ = writeln!(
            out,
            "    require_{}: assume property ({clk_event} disable iff ({rst_sv}) ({}));",
            r.label,
            expr_to_sv(&r.expr)
        );
    }

    // `invariant` -> `assert property`
    for inv in &contract.invariants {
        let d = max_prev_depth(&inv.expr);
        let guard = if d > 0 {
            format!("(vf_hist >= 8'd{d}) |-> ")
        } else {
            String::new()
        };
        let _ = writeln!(
            out,
            "    invariant_{}: assert property ({clk_event} disable iff ({rst_sv}) {guard}({}));",
            inv.label,
            expr_to_sv(&inv.expr)
        );
    }

    // `operation ... when ... { ensure ... }`
    for op in &contract.operations {
        let trig_sv = expr_to_sv(&op.trigger);
        for ens in &op.ensures {
            let pname = format!("op_{}_{}", op.name, ens.label);
            match &ens.timing {
                EnsureTiming::After(n) => {
                    let resp_sv = expr_to_sv_with_past(&ens.response, *n);
                    let _ = writeln!(
                        out,
                        "    {pname}: assert property ({clk_event} disable iff ({rst_sv}) ({trig_sv}) |-> ##{n} ({resp_sv}));"
                    );
                }
                EnsureTiming::Within(a, b) => {
                    let resp_sv = expr_to_sv_with_past(&ens.response, *a);
                    let _ = writeln!(
                        out,
                        "    {pname}: assert property ({clk_event} disable iff ({rst_sv}) ({trig_sv}) |-> ##[{a}:{b}] ({resp_sv}));"
                    );
                }
                EnsureTiming::Until(ev) => {
                    let ev_sv = expr_to_sv(ev);
                    let resp_sv = expr_to_sv(&ens.response);
                    let _ = writeln!(
                        out,
                        "    {pname}: assert property ({clk_event} disable iff ({rst_sv}) ({trig_sv}) |=> (({resp_sv}) until ({ev_sv})));"
                    );
                }
                EnsureTiming::Eventually => {
                    let resp_sv = expr_to_sv(&ens.response);
                    let _ = writeln!(
                        out,
                        "    {pname}: assert property ({clk_event} disable iff ({rst_sv}) ({trig_sv}) |-> s_eventually ({resp_sv}));"
                    );
                }
            }
        }
    }

    // `fair`, `eventually`, `cover`
    for f in &contract.fairs {
        let _ = writeln!(
            out,
            "    fair_{}: assume property ({clk_event} s_eventually ({}));",
            f.label,
            expr_to_sv(&f.expr)
        );
    }
    for ev in &contract.eventuallys {
        let _ = writeln!(
            out,
            "    eventually_{}: assert property ({clk_event} s_eventually ({}));",
            ev.label,
            expr_to_sv(&ev.expr)
        );
    }
    for cov in &contract.covers {
        let _ = writeln!(
            out,
            "    cover_{}: cover property ({clk_event} disable iff ({rst_sv}) ({}));",
            cov.label,
            expr_to_sv(&cov.expr)
        );
    }

    let _ = writeln!(out, "endmodule\n");

    // Emit IEEE 1800 `bind` statement!
    let _ = write!(
        out,
        "bind {} {chk_name} u_{} (",
        contract.target_module, contract.name
    );
    for (i, pname) in port_list.iter().enumerate() {
        let comma = if i + 1 < port_list.len() { ", " } else { "" };
        let _ = write!(out, ".{pname}({pname}){comma}");
    }
    out.push_str(");\n");

    out
}

fn emit_sv_update_stmts(stmts: &[UpdateStmt], indent: usize, out: &mut String) {
    let pad = "    ".repeat(indent);
    for s in stmts {
        match s {
            UpdateStmt::Assign { target, value, .. } => {
                let _ = writeln!(out, "{pad}{target} <= {};", expr_to_sv(value));
            }
            UpdateStmt::If {
                cond,
                then_body,
                else_body,
                ..
            } => {
                let _ = writeln!(out, "{pad}if ({}) begin", expr_to_sv(cond));
                emit_sv_update_stmts(then_body, indent + 1, out);
                if else_body.is_empty() {
                    let _ = writeln!(out, "{pad}end");
                } else {
                    let _ = writeln!(out, "{pad}end else begin");
                    emit_sv_update_stmts(else_body, indent + 1, out);
                    let _ = writeln!(out, "{pad}end");
                }
            }
        }
    }
}

fn expr_to_sv(e: &Expr) -> String {
    expr_to_sv_with_past(e, 1)
}

fn expr_to_sv_with_past(e: &Expr, trig_delay: u32) -> String {
    match &e.kind {
        ExprKind::Bool(b) => if *b { "1'b1" } else { "1'b0" }.to_string(),
        ExprKind::Int(v) => v.to_string(),
        ExprKind::SizedLit {
            width,
            signed,
            bits,
        } => {
            let s = if *signed { "s" } else { "" };
            format!("{width}'{s}b{bits}")
        }
        ExprKind::Ident(s) => s.clone(),
        ExprKind::Unary { op, expr } => {
            let sym = match op {
                UnOp::LogNot => "!",
                UnOp::BitNot => "~",
                UnOp::Neg => "-",
            };
            format!("({sym}{})", expr_to_sv_with_past(expr, trig_delay))
        }
        ExprKind::Binary { op, left, right } => {
            let l = expr_to_sv_with_past(left, trig_delay);
            let r = expr_to_sv_with_past(right, trig_delay);
            if *op == BinOp::Implies {
                return format!("((!({l})) || ({r}))");
            }
            let sym = match op {
                BinOp::LogOr => "||",
                BinOp::LogAnd => "&&",
                BinOp::BitOr => "|",
                BinOp::BitXor => "^",
                BinOp::BitAnd => "&",
                BinOp::Eq => "==",
                BinOp::Ne => "!=",
                BinOp::Lt => "<",
                BinOp::Le => "<=",
                BinOp::Gt => ">",
                BinOp::Ge => ">=",
                BinOp::Shl => "<<",
                BinOp::Shr => ">>",
                BinOp::Add => "+",
                BinOp::Sub => "-",
                BinOp::Mul => "*",
                BinOp::Div => "/",
                BinOp::Mod => "%",
                BinOp::Implies => unreachable!(),
            };
            format!("({l} {sym} {r})")
        }
        ExprKind::Ternary {
            cond,
            then_expr,
            else_expr,
        } => format!(
            "({} ? {} : {})",
            expr_to_sv_with_past(cond, trig_delay),
            expr_to_sv_with_past(then_expr, trig_delay),
            expr_to_sv_with_past(else_expr, trig_delay)
        ),
        ExprKind::Slice { expr, hi, lo } => {
            let inner = expr_to_sv_with_past(expr, trig_delay);
            if hi == lo {
                format!("{inner}[{hi}]")
            } else {
                format!("{inner}[{hi}:{lo}]")
            }
        }
        ExprKind::Concat(parts) => {
            let ps: Vec<String> = parts
                .iter()
                .map(|p| expr_to_sv_with_past(p, trig_delay))
                .collect();
            format!("{{{}}}", ps.join(", "))
        }
        ExprKind::Call { name, args } => match name.as_str() {
            "at_trigger" => {
                let inner = expr_to_sv_with_past(&args[0], trig_delay);
                format!("$past({inner}, {trig_delay})")
            }
            "prev" => {
                let inner = expr_to_sv_with_past(&args[0], trig_delay);
                if args.len() == 2 {
                    format!("$past({inner}, {})", expr_to_sv_with_past(&args[1], trig_delay))
                } else {
                    format!("$past({inner})")
                }
            }
            "rose" => format!("$rose({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "fell" => format!("$fell({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "stable" => format!("$stable({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "changed" => format!("$changed({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "onehot" => format!("$onehot({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "onehot0" => format!("$onehot0({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "countones" => format!("$countones({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "unsigned" => format!("$unsigned({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "signed" => format!("$signed({})", expr_to_sv_with_past(&args[0], trig_delay)),
            "resize" => format!(
                "{}'({})",
                expr_to_sv_with_past(&args[1], trig_delay),
                expr_to_sv_with_past(&args[0], trig_delay)
            ),
            "ite" => format!(
                "({} ? {} : {})",
                expr_to_sv_with_past(&args[0], trig_delay),
                expr_to_sv_with_past(&args[1], trig_delay),
                expr_to_sv_with_past(&args[2], trig_delay)
            ),
            other => {
                let a: Vec<String> = args
                    .iter()
                    .map(|x| expr_to_sv_with_past(x, trig_delay))
                    .collect();
                format!("{other}({})", a.join(", "))
            }
        },
    }
}

fn collect_idents(e: &Expr, locals: &BTreeSet<String>, out: &mut BTreeSet<String>) {
    match &e.kind {
        ExprKind::Ident(s) => {
            if !locals.contains(s) {
                out.insert(s.clone());
            }
        }
        ExprKind::Unary { expr, .. } | ExprKind::Slice { expr, .. } => {
            collect_idents(expr, locals, out)
        }
        ExprKind::Binary { left, right, .. } => {
            collect_idents(left, locals, out);
            collect_idents(right, locals, out);
        }
        ExprKind::Ternary {
            cond,
            then_expr,
            else_expr,
        } => {
            collect_idents(cond, locals, out);
            collect_idents(then_expr, locals, out);
            collect_idents(else_expr, locals, out);
        }
        ExprKind::Call { args, .. } | ExprKind::Concat(args) => {
            for a in args {
                collect_idents(a, locals, out);
            }
        }
        ExprKind::Bool(_) | ExprKind::Int(_) | ExprKind::SizedLit { .. } => {}
    }
}

fn collect_update_idents(stmts: &[UpdateStmt], locals: &BTreeSet<String>, out: &mut BTreeSet<String>) {
    for s in stmts {
        match s {
            UpdateStmt::Assign { value, .. } => collect_idents(value, locals, out),
            UpdateStmt::If {
                cond,
                then_body,
                else_body,
                ..
            } => {
                collect_idents(cond, locals, out);
                collect_update_idents(then_body, locals, out);
                collect_update_idents(else_body, locals, out);
            }
        }
    }
}

fn max_prev_depth(e: &Expr) -> u32 {
    match &e.kind {
        ExprKind::Call { name, args } => {
            let self_d = match name.as_str() {
                "prev" => {
                    if let Some(Expr {
                        kind: ExprKind::Int(n),
                        ..
                    }) = args.get(1)
                    {
                        *n as u32
                    } else {
                        1
                    }
                }
                "rose" | "fell" | "stable" | "changed" => 1,
                _ => 0,
            };
            args.iter()
                .map(max_prev_depth)
                .fold(self_d, std::cmp::max)
        }
        ExprKind::Unary { expr, .. } | ExprKind::Slice { expr, .. } => max_prev_depth(expr),
        ExprKind::Binary { left, right, .. } => max_prev_depth(left).max(max_prev_depth(right)),
        ExprKind::Ternary {
            cond,
            then_expr,
            else_expr,
        } => max_prev_depth(cond)
            .max(max_prev_depth(then_expr))
            .max(max_prev_depth(else_expr)),
        ExprKind::Concat(parts) => parts.iter().map(max_prev_depth).max().unwrap_or(0),
        _ => 0,
    }
}
